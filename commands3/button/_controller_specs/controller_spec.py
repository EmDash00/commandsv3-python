from dataclasses import dataclass


@dataclass(frozen=True)
class ButtonSpec:
    enum_member: str
    method: str
    stem: str
    label: str


@dataclass(frozen=True)
class AxisSpec:
    enum_member: str
    stem: str
    label: str
    getter: str
    deadband_setter: str
    positive_direction: str


@dataclass(frozen=True)
class ControllerSpec:
    filename: str
    wrapper_class: str
    controller_class: str
    buttons: tuple[ButtonSpec, ...]
    axes: tuple[AxisSpec, ...]
    module_doc: str = "Autogenerated using :module:`_commands3.button._autogen`"
